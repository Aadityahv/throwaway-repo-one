#!/usr/bin/env python3
"""Port-support report of the machine-learning, tensor-core and attention kernels on sm_90 (H100) and sm_80 (A100) (CPU only; deterministic; reads no measured value).

    python make_port_support_report.py            # writes PORT_SUPPORT_ML.md
    python make_port_support_report.py --check    # exit 1 unless the committed report equals the regenerated one

Per kernel and architecture: the instruction forms the compiler (CUDA 12.1) emitted into the committed SASS dump of the combined driver, which of them only the port extensions
(port_ext.py, port_ml_ext.py) interpret, whether every cell that launches the kernel is supported by the static side (from ml_sets/static_support_*_<arch>.json, when built) with the
exact reason otherwise, and, for tensor instructions, whether the form is the one the calibrator's tensor stage measures and prices. No cell is dropped: an unsupported cell is listed.
"""
from __future__ import annotations

import argparse
import collections
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FZ = HERE.parent
SR = FZ.parent
sys.path.insert(0, str(SR / "port_common"))
sys.path.insert(0, str(HERE))
OUT = HERE / "PORT_SUPPORT_ML.md"
ARCH = {"sm_90": ("h100", "port_h100"), "sm_80": ("a100", "port_a100")}
TENSOR_PRICED_FORM = "HMMA.16816.F32.BF16"      # csrc/micro_tensor.cu issues exactly this form; cal/tensor.py prices every `tensor_core` instruction at its measured rate
OP = re.compile(r"/\*[0-9a-f]{4}\*/\s+(?:@!?U?P\w+\s+)?([A-Z][A-Z0-9_.]*)")


def kernels():
    import make_sass_manifest_ml as MSM
    return MSM.KERNELS, MSM.functions


def opcode_forms(text):
    c = collections.Counter(OP.findall(text))
    return dict(sorted(c.items()))


def build():
    import port_ext as PX
    import port_ml_ext as PM
    KERNELS, functions = kernels()
    extension_ops = set(PX.PORT_OPS) | set(PM.ML_OPS)
    lines = ["# Port support of the machine-learning, tensor-core and attention kernels (generated by make_port_support_report.py; do not edit)", ""]
    lines.append("Source: the committed CUDA 12.1.66 SASS dump of the combined driver (`port_<arch>/compiled_cluster_cuda12.1_ml/driver_ml.sass`, build record `build.txt`). Static analysis: "
                 "`port_common/port_ml_ext.py` on top of `port_ext.py`; Blackwell is unchanged (test_port_ext.py, test_set_d_port.py). `port ext` marks forms only the extensions interpret; "
                 "`tensor` marks forms priced by the tensor stage.")
    lines.append("")
    for sm, (arch, folder) in ARCH.items():
        text = (SR / folder / "compiled_cluster_cuda12.1_ml" / "driver_ml.sass").read_text(encoding="utf-8", errors="replace")
        funcs = functions(text)
        cells = {}
        support = {}
        for which in ("ml", "tensor"):
            cf, sf = HERE / ("cells_%s_%s.json" % (which, arch)), HERE / ("static_support_%s_%s.json" % (which, arch))
            for c in json.loads(cf.read_text())["cells"]:
                cells[c["cell_id"]] = c
            if sf.is_file():
                support.update(json.loads(sf.read_text())["rows"])
        lines += ["## %s (%s)" % (arch.upper(), sm), ""]
        lines.append("| Kernel | Set | Cells | Supported cells | Instruction forms in the SASS (count) | Status |")
        lines.append("|---|---|---:|---:|---|---|")
        notes = []
        for kid, (needle, which) in sorted(KERNELS.items(), key=lambda kv: (kv[1][1] != "ml", kv[0])):
            sym = next(s for s in funcs if needle in s)
            forms = opcode_forms(funcs[sym])
            mine = [c for c in cells.values() if any(k["kid"] == kid for k in c["kernels"])]
            sup = [c for c in mine if c["cell_id"] in support and support[c["cell_id"]]["supported"]]
            built = all(c["cell_id"] in support for c in mine) and bool(mine)
            def fmt(o, n):
                tag = ""
                if o in extension_ops:
                    tag += " [port ext]"
                if o.startswith(("HMMA", "IMMA", "QMMA", "DMMA")):
                    tag += " [tensor%s]" % ("" if o == TENSOR_PRICED_FORM else ", NOT the measured form")
                return "%s%s x%d" % (o, tag, n)
            status = "static tables not built" if not built else ("all supported" if len(sup) == len(mine) else "%d UNSUPPORTED" % (len(mine) - len(sup)))
            lines.append("| %s | %s | %d | %s | %s | %s |" % (kid, which, len(mine), len(sup) if built else "-", "; ".join(fmt(o, n) for o, n in forms.items()), status))
            for c in mine:
                if built and not support[c["cell_id"]]["supported"]:
                    notes.append("- `%s`: %s" % (c["cell_id"], (support[c["cell_id"]]["reason"] or "").replace("|", "/")[:400]))
        lines.append("")
        lines.append("Unsupported cells (each is a failure in every score, listed with the exact reason):" if notes else "No unsupported cell.")
        lines += notes + [""]
    return "\n".join(lines).rstrip() + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = build().encode("utf-8")
    if a.check:
        if not OUT.is_file() or OUT.read_bytes() != text:
            print("PORT_SUPPORT_ML.md differs from the regenerated report", file=sys.stderr)
            return 1
        return 0
    OUT.write_bytes(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
